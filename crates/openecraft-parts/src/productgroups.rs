fn id_of(table: &[(u16, &str)], name: &str) -> Option<u16> {
    let name = name.trim();
    table.iter().find(|(_, n)| n.eq_ignore_ascii_case(name)).map(|(id, _)| *id)
}

fn name_of(table: &[(u16, &'static str)], id: u16) -> Option<&'static str> {
    table.iter().find(|(i, _)| *i == id).map(|(_, n)| *n)
}

/// EPLAN number of a product group (EPLAN name or one of OpenECraft's own groups).
pub fn group_id(name: &str) -> Option<u16> {
    id_of(GROUPS, name).or_else(|| GROUP_ALIASES.iter().find(|(n, _)| n.eq_ignore_ascii_case(name.trim())).map(|(_, id)| *id))
}

pub fn group_name(id: u16) -> Option<&'static str> {
    name_of(GROUPS, id)
}

pub fn subgroup_id(name: &str) -> Option<u16> {
    id_of(SUBGROUPS, name)
}

pub fn subgroup_name(id: u16) -> Option<&'static str> {
    name_of(SUBGROUPS, id)
}

/// The EPLAN numbers of a part's groups (0: undefined).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Classification {
    pub top_group: u16,
    pub group: u16,
    pub subgroup: u16,
}

pub fn classify(part: &Part) -> Classification {
    Classification {
        top_group: part.top_group.eplan_id(),
        group: group_id(&part.group).unwrap_or(0),
        subgroup: subgroup_id(&part.subgroup).unwrap_or(0),
    }
}

/// Sets the groups of a part from EPLAN numbers; unknown or undefined numbers keep
/// the part's text.
pub fn apply(part: &mut Part, c: Classification) {
    if let Some(t) = TopGroup::from_eplan_id(c.top_group) {
        part.top_group = t;
    }
    if let Some(g) = group_name(c.group).filter(|_| c.group != 0) {
        part.group = g.into();
    }
    if let Some(s) = subgroup_name(c.subgroup).filter(|_| c.subgroup != 0) {
        part.subgroup = s.into();
    }
}

